// Optional QA: npm install --no-save --package-lock=false playwright
// Start npm start first, then: node scripts/browser-check.mjs
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({channel:'msedge',headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto('http://127.0.0.1:4173');
  await page.locator('.hero').waitFor();
  await mkdir('docs',{recursive:true});
  await page.screenshot({path:'docs/screenshot.png',fullPage:true});
  assert.equal(await page.locator('.level-card:disabled').count(),7);
  await page.locator('.level-card').first().click();
  await page.locator('[data-card="0"]').selectOption('猫');
  await page.locator('#reason').fill('模糊和错误标签会影响模型学到的规律。');
  await page.locator('button[type="submit"]').click();
  assert.ok(await page.locator('#feedback').textContent());
  // Complete every task without assistance.
  const options=await page.locator('[data-card]').evaluateAll(nodes=>nodes.map(n=>n.dataset.card));
  for(const id of options) await page.locator(`[data-card="${id}"]`).selectOption(Number(id)<22?['猫','狗','其他'][Number(id)%3]:'剔除');
  await page.locator('button[type="submit"]').click();
  await page.locator('#next-stage').click();
  await page.locator('#epochs').fill('10');
  await page.locator('#reason').fill('新样本和训练数据不同，模型也有能力局限。');
  await page.locator('#train-choice').selectOption('1');
  await page.locator('button[type="submit"]').click();
  await page.locator('#next-stage').click();
  for(const [i,v] of ['0','1','1','0','1'].entries()) await page.locator(`#sample-${i}`).selectOption(v);
  await page.locator('#confidence').selectOption('1');
  await page.locator('button[type="submit"]').click();
  await page.locator('#next-stage').click();
  for(let i=0;i<3;i++) await page.locator(`#cat-${i}`).fill('8');
  await page.locator('#fairness').selectOption('1');
  await page.locator('button[type="submit"]').click();
  await page.locator('#next-stage').click();
  await page.locator('#prompt').fill('画一只戴宇航员头盔的橘猫，卡通风格，火星背景。');
  await page.locator('#generate').click();
  await page.locator('#prompt').fill('画一只戴宇航员头盔的橘猫，卡通风格，火星背景，探索岩石。');
  await page.locator('button[type="submit"]').click();
  assert.ok((await page.locator('#feedback').textContent()).includes('重新生成'));
  await page.locator('#generate').click();
  await page.locator('button[type="submit"]').click();
  await page.locator('#next-stage').click();
  for(const [i,v] of ['0','1','1'].entries()) await page.locator(`#claim-${i}`).selectOption(v);
  await page.locator('#evidence').fill('资料说小蓝只能在室内行走，不会飞到月球；温室每周三而不是每天浇水。');
  await page.locator('button[type="submit"]').click();
  await page.locator('#next-stage').click();
  for(const i of [1,3,5]) await page.locator(`[name="ethics"][value="${i}"]`).check();
  await page.locator('#rule-privacy').fill('不上传人脸，优先使用不包含个人信息的素材。');
  await page.locator('#rule-copyright').fill('检查授权并注明来源，不随意复制他人作品。');
  await page.locator('#rule-responsibility').fill('由老师审核并提供纠错渠道，记录改进过程。');
  await page.locator('button[type="submit"]').click();
  await page.locator('#next-stage').click();
  for(const id of ['problem','sense','think','act','tech-reason']) await page.locator(`#${id}`).fill('图书馆助手读取书架编号，帮助同学找到书，失败时请老师帮助。');
  await page.locator('#tech').selectOption('0');
  await page.locator('#reviewed').check();
  await page.locator('button[type="submit"]').click();
  await page.locator('#next-stage').click();
  assert.equal(await page.locator('.badge.earned').count(),8);
  await page.locator('.collab').nth(2).check();
  assert.equal(await page.locator('.collab').nth(2).isChecked(),true);
  assert.equal(await page.locator('.collab').nth(0).isChecked(),false);
  await page.locator('.collab').nth(2).uncheck();
  await page.locator('.collab').nth(0).check();
  await page.locator('.collab').nth(1).check();
  assert.ok((await page.locator('main').textContent()).includes('金牌 AI 训练师'));
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#export').click();
  const download=await downloadPromise;
  assert.equal(download.suggestedFilename(),'AI星球-训练师护照.json');
  await page.reload();
  assert.equal(await page.locator('#progress-label').textContent(),'8 / 8');
  await page.locator('.nav-button[data-view="teacher"]').click();
  assert.ok((await page.locator('main').textContent()).includes('课堂节奏'));
  await page.setViewportSize({width:390,height:844});
  await page.locator('.nav-button[data-view="map"]').click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'docs/mobile-screenshot.png',fullPage:true});
  await page.locator('.level-card').first().click();
  assert.ok(await page.evaluate(()=>{const d=document.querySelector('dialog');return d.scrollWidth<=d.clientWidth;}));
  await page.locator('#close-dialog').click();
  // Storage corruption must not crash the UI.
  await page.evaluate(()=>localStorage.setItem('ai-planet-v1','{corrupt'));
  await page.reload();
  assert.equal(await page.locator('#progress-label').textContent(),'0 / 8');
  await page.locator('.level-card').first().click();
  await page.locator('#hint').click();
  await page.locator('#assist').click();
  assert.equal(await page.locator('[data-card="29"]').inputValue(),'剔除');
  await page.locator('#reason').fill('模糊数据缺少信息，错标签会误导模型学习。');
  await page.locator('button[type="submit"]').click();
  assert.ok((await page.locator('.success-panel').textContent()).includes('60 分'));
  assert.deepEqual(errors,[]);
  console.log('Browser QA passed: 8 stages, validation, awards, export, persistence, mobile, corruption, hints and assistance. No page errors.');
} finally { await browser.close(); }
